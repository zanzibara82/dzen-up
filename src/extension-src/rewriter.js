  // --- Псевдослучайность с сидом (результат стабилен для одного текста) ------
  function makeRandom(seed) {
    var s = seed >>> 0 || 1;
    return function () {
      s ^= s << 13;
      s ^= s >>> 17;
      s ^= s << 5;
      s >>>= 0;
      return s / 4294967296;
    };
  }

  function hash(str) {
    var h = 2166136261;
    for (var i = 0; i < str.length; i++) {
      h ^= str.charCodeAt(i);
      h = (h * 16777619) >>> 0;
    }
    return h;
  }

  function matchCase(sample, word) {
    if (!sample) return word;
    if (sample[0] === sample[0].toUpperCase() && sample[0] !== sample[0].toLowerCase()) {
      return word.charAt(0).toUpperCase() + word.slice(1);
    }
    return word;
  }

  function capitalize(s) {
    return s.charAt(0).toUpperCase() + s.slice(1);
  }

  function lowerFirst(s) {
    // Не трогаем аббревиатуры вида "СССР" и имена в кавычках
    if (/^[A-ZА-ЯЁ]{2,}/.test(s)) return s;
    return s.charAt(0).toLowerCase() + s.slice(1);
  }

  function splitSentences(text) {
    var parts = text.match(/[^.!?…]+(?:[.!?…]+["»)]?|$)/g);
    return parts ? parts.filter(function (p) { return p.trim().length; }) : [];
  }

  // --- Основная функция ------------------------------------------------------
  /**
   * @param {string} text  исходный (уже переведённый) текст
   * @param {{strength?: 'light'|'medium'|'strong', seed?: number}} opts
   */
  function rewrite(text, opts) {
    opts = opts || {};
    var strength = opts.strength || "medium";
    var rnd = makeRandom(typeof opts.seed === "number" ? opts.seed : hash(text));

    var cfg = {
      light: { syn: 0.4, phrase: 0.6, opener: 0.1, split: 0.3 },
      medium: { syn: 0.75, phrase: 0.9, opener: 0.22, split: 0.6 },
      strong: { syn: 1, phrase: 1, opener: 0.38, split: 0.9 }
    }[strength] || { syn: 0.75, phrase: 0.9, opener: 0.22, split: 0.6 };

    var paragraphs = String(text).replace(/\r\n/g, "\n").split(/\n{1,}/);

    var out = paragraphs.map(function (para) {
      if (!para.trim()) return "";

      var t = para;

      // 1. Обороты
      PHRASES.forEach(function (rule) {
        t = t.replace(rule[0], function (m) {
          if (rnd() > cfg.phrase) return m;
          var variants = rule[1];
          var repl = variants[Math.floor(rnd() * variants.length)];
          return matchCase(m, repl);
        });
      });

      // 2. Синонимы (по словам)
      t = t.replace(/[А-Яа-яЁё]{3,}/g, function (word) {
        var key = word.toLowerCase();
        var variants = SYNONYMS[key];
        if (!variants) return word;
        if (rnd() > cfg.syn) return word;
        return matchCase(word, variants[Math.floor(rnd() * variants.length)]);
      });

      // 3. Работа с предложениями
      var sentences = splitSentences(t);
      var rebuilt = [];

      sentences.forEach(function (raw, idx) {
        var s = raw.trim();
        if (!s) return;

        // 3a. Разбивка длинных предложений
        if (s.length > 150 && rnd() < cfg.split) {
          var cut = s.replace(/,\s+(и|а|но|однако|при этом)\s+/i, function (m, conj, offset) {
            if (offset < 60 || offset > s.length - 40) return m;
            var tail = conj.toLowerCase();
            if (tail === "и" || tail === "а") return ". ";
            return ". " + capitalize(tail) + " ";
          });
          if (cut !== s) {
            s = cut.replace(/\.\s+([а-яё])/g, function (m, ch) {
              return ". " + ch.toUpperCase();
            });
          }
        }

        // 3b. Вводные слова
        if (idx > 0 && rnd() < cfg.opener && s.length > 45 && !/^[«"(\d]/.test(s)) {
          var opener = OPENERS[Math.floor(rnd() * OPENERS.length)];
          s = opener + lowerFirst(s);
        }

        rebuilt.push(s);
      });

      var result = rebuilt.join(" ");

      // 4. Косметика
      result = result
        .replace(/\s+([,.;:!?])/g, "$1")
        .replace(/\s{2,}/g, " ")
        .replace(/—\s*—/g, "—")
        .replace(/(^|[.!?…]\s+)([а-яё])/g, function (m, p1, p2) {
          return p1 + p2.toUpperCase();
        })
        .trim();

      return result;
    });

    return out.join("\n\n").replace(/\n{3,}/g, "\n\n").trim();
  }

  // --- Оценка уникальности: доля новых 3-грамм -------------------------------
  function uniqueness(original, rewritten) {
    function shingles(s) {
      var words = String(s)
        .toLowerCase()
        .replace(/[^0-9a-zа-яё\s]/gi, " ")
        .split(/\s+/)
        .filter(Boolean);
      var set = new Set();
      for (var i = 0; i < words.length; i++) {
        set.add(words.slice(i, i + 3).join(" "));
      }
      return set;
    }
    var a = shingles(original);
    var b = shingles(rewritten);
    if (!b.size) return 0;
    var fresh = 0;
    b.forEach(function (sh) {
      if (!a.has(sh)) fresh++;
    });
    return Math.round((fresh / b.size) * 100);
  }

  function stats(text) {
    var clean = String(text).trim();
    var words = clean ? clean.split(/\s+/).length : 0;
    return {
      chars: clean.length,
      words: words,
      readMinutes: Math.max(1, Math.round(words / 180))
    };
  }

  root.DzenRewriter = {
    rewrite: rewrite,
    uniqueness: uniqueness,
    stats: stats,
    splitSentences: splitSentences
  };
